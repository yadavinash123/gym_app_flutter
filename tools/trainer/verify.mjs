import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium} from 'playwright';
import validator from 'gltf-validator';

const root=resolve(import.meta.dirname,'../..');
const bytes=await readFile(root+'/assets/trainer/push-up.glb');
const manifest=JSON.parse(await readFile(root+'/assets/trainer/manifest.json','utf8')).assets[0];
const validation=await validator.validateBytes(new Uint8Array(bytes),{uri:'push-up.glb',maxIssues:50});
await writeFile('/tmp/fitforge-glb-validation.json',JSON.stringify(validation,null,2));
assert.equal(validation.issues.numErrors,0,'GLB validation errors');
const browser=await chromium.launch({executablePath:process.env.CHROME_BIN||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
try {
 const page=await browser.newPage({viewport:{width:342,height:740},deviceScaleFactor:1});
 const errors=[], requests=[], messages=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
 await page.route(/^https?:/,route=>route.abort());
 await page.exposeFunction('recordMessage',x=>messages.push(JSON.parse(x)));
 await page.addInitScript(()=>window.TrainerBridge={postMessage:window.recordMessage});
 await page.goto('file://'+root+'/assets/trainer/index.html');
 const options={clips:manifest.clips,phases:manifest.phases};
 await page.evaluate(async ({b,o})=>window.fitforge.load(b,o),{b:bytes.toString('base64'),o:options});
 const snapshot=()=>page.evaluate(()=>window.fitforge.snapshot());
 const start=await snapshot();assert.equal(start.ready,true);assert.equal(start.skinnedMeshes,1);assert.equal(start.playing,false);
 await page.screenshot({path:'/tmp/fitforge-3d-start.png'});
 await page.evaluate(()=>window.fitforge.seek(.75));
 const middle=await snapshot();assert.notDeepEqual(middle.bones,start.bones,'Bone transforms must change when seeking');
 await page.screenshot({path:'/tmp/fitforge-3d-mid.png'});
 await page.click('#play'); await page.waitForTimeout(200);assert.equal((await snapshot()).playing,true);
 await page.click('#play'); const stopped=(await snapshot()).time; await page.waitForTimeout(150);assert.equal((await snapshot()).time,stopped);
 await page.click('[data-view=front]');const front=(await snapshot()).camera;
 await page.click('[data-view=back]');assert.notDeepEqual((await snapshot()).camera,front);
 await page.click('#zoom-in'); const zoomed=(await snapshot()).camera;
 await page.click('#zoom-out');assert.notDeepEqual((await snapshot()).camera,zoomed);
 await page.check('#highlight');await page.screenshot({path:'/tmp/fitforge-3d-muscles.png'});
 await page.uncheck('#loop');await page.selectOption('#speed','1.5');await page.evaluate(()=>window.fitforge.seek(1.45));await page.click('#play');await page.waitForTimeout(300);assert.equal((await snapshot()).playing,false);assert.equal((await snapshot()).time,start.duration);
 await page.click('#fullscreen');assert(messages.some(m=>m.type==='fullscreen'));
 await page.evaluate(()=>window.fitforge.setReduced(true));assert.equal(await page.isDisabled('#play'),true);await page.evaluate(()=>window.fitforge.seek(.5));assert.equal((await snapshot()).time,.5);
 await page.evaluate(()=>{window.fitforge.setReduced(false);window.fitforge.setActive(false);});await page.click('#play');assert.equal((await snapshot()).playing,false);
 await page.evaluate(()=>window.fitforge.setActive(true));await page.click('#play');await page.evaluate(()=>window.fitforge.setActive(false));assert.equal((await snapshot()).playing,false);
 await page.evaluate(()=>window.fitforge.setActive(true));
 await page.evaluate(async ({b,o})=>window.fitforge.load(b,{...o,clips:['not-a-pushup']}),{b:bytes.toString('base64'),o:options});assert.equal((await snapshot()).ready,false);assert.match((await snapshot()).error,/missing/);
 await page.evaluate(async ({b,o})=>window.fitforge.load(b,{...o,startTime:.6,fullscreen:true}),{b:bytes.toString('base64'),o:options});assert.equal((await snapshot()).ready,true);assert.equal((await snapshot()).time,.6);assert.equal(await page.isVisible('#fullscreen'),false);
 await page.evaluate(()=>window.fitforge.dispose());
 assert.deepEqual(errors,[]);assert.deepEqual(requests,[],'Viewer must not request remote assets');
 console.log(JSON.stringify({result:'PASS',glbErrors:validation.issues.numErrors,glbWarnings:validation.issues.numWarnings,bones:start.bones.length,duration:start.duration,checks:['actual model loading','bone deformation on seek','play/pause','camera views','zoom','muscle emphasis','speed and nonloop ending','fullscreen bridge','reduced motion','background pause','missing clip rejection','retry','initial seek','offline network','disposal']},null,2));
} finally { await browser.close(); }
